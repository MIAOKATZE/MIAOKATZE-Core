/** Runs only with the explicit fakes generated by run-bq-shared-sync-contracts.py. */
public final class BqSharedSyncRegression {

    private static final UUID QUEST = new UUID(0, 100);
    private static final UUID CHAPTER = new UUID(0, 200);
    private static final UUID ONLINE = new UUID(0, 1);
    private static final UUID OFFLINE = new UUID(0, 2);
    private static int checks;

    public static void main(String[] args) throws Exception {
        startupRace(false);
        startupRace(true);
        localPartialAndProgress();
        runtimeReloadAndStaleSnapshot();
        remoteSync();
        chapterSync();
        loaderAndSessionBoundaries();
        System.out.println("PASS " + checks + " assertions; original BQ sync/PacketSender sources, dependency fakes; no game or Mixin transform.");
    }

    private static void startupRace(boolean guarded) throws Exception {
        Quest original = reset(true, true);
        // Original external startup reinjector; registration and disk replay dependencies are fakes.
        java.lang.reflect.Field debounce = BQReinjector.class.getDeclaredField("lastReinjectMs");
        debounce.setAccessible(true);
        ((AtomicLong) debounce.get(null)).set(0);
        BQReinjector.reinject(FMLCommonHandler.instance().server);
        check(BQApi.calls == 1 && BQManagedQuestProgress.calls == 1
            && betterquesting.handlers.SaveLoadHandler.INSTANCE.dirty == 1,
            "real external reinjector calls registration/replay and marks dirty");
        check(BQThreadedIO.INSTANCE.queue.size() == 2, "no online player => quest and chapter configs only; no progress jobs");
        BQThreadedIO.INSTANCE.step();
        check(BQThreadedIO.INSTANCE.queue.size() == 2, "real PacketSender enqueues a second broadcast job behind chapter serialization");
        check(BetterQuesting.instance.network.delivered.isEmpty(), "packet not delivered before second job");
        login();
        BQThreadedIO.INSTANCE.drain();
        check(BetterQuesting.instance.network.delivered.size() == 2, "login between queues receives quest and chapter startup broadcasts");
        NBTTagCompound payload = delivered();
        check(!payload.getBoolean("merge"), "startup config is a replacing full-book packet");
        check(!payload.getTagList("data", 10).getCompoundTagAt(0).hasKey("progress"), "startup config carries no progress");
        receive(NetQuestSync.class, payload, guarded);
        Quest result = quest();
        if (guarded) {
            check(result == original && result.progress.get(ONLINE) == 7 && result.progress.get(OFFLINE) == 13,
                "guard preserves shared identity and both online/offline progress");
            check(result.claims.get(ONLINE) == 1 && result.claims.get(OFFLINE) == 2,
                "guard preserves both users' claim state alongside partial task amounts");
            check(QuestDatabase.INSTANCE.clears == 0, "guard never clears shared quest storage");
        } else {
            check(result != original && result.progress.isEmpty() && result.claims.isEmpty(),
                "old native handler loses all progress/claim state and quest identity");
            check(QuestDatabase.INSTANCE.clears == 1, "old native handler clears the shared database");
        }
        event(DBType.QUEST);
        System.out.println((guarded ? "FIXED" : "OLD FAILURE REPRODUCED") + ": zero-online startup, delayed broadcast delivered after login");
    }

    private static void localPartialAndProgress() throws Exception {
        Quest original = reset(true, true);
        login();
        NetQuestSync.sendSync(null, Collections.singletonList(QUEST), true, false);
        BQThreadedIO.INSTANCE.drain();
        receive(NetQuestSync.class, delivered(), true);
        check(quest() == original && original.progress.get(OFFLINE) == 13, "partial config must not rebuild shared tasks");
        event(DBType.QUEST);

        resetDelivery();
        NetQuestSync.sendSync(FMLCommonHandler.instance().server.manager.playerEntityList.get(0), null, false, true, true);
        BQThreadedIO.INSTANCE.drain();
        NBTTagCompound oldProgress = delivered();
        original.progress.put(ONLINE, 21);
        receive(NetQuestSync.class, oldProgress, true);
        check(original.progress.get(ONLINE) == 21 && original.progress.get(OFFLINE) == 13,
            "old progress reply must not roll back the authoritative shared database");
        event(DBType.QUEST);
    }

    private static void runtimeReloadAndStaleSnapshot() throws Exception {
        reset(true, true);
        login();
        NetQuestSync.sendSync(null, null, true, false);
        BQThreadedIO.INSTANCE.step(); // snapshot is older than the administrator's reload
        Quest reloaded = new Quest();
        reloaded.definition = 42;
        reloaded.progress.put(ONLINE, 55);
        reloaded.progress.put(OFFLINE, 89);
        QuestDatabase.INSTANCE.put(QUEST, reloaded);
        BQThreadedIO.INSTANCE.drain();
        receive(NetQuestSync.class, delivered(), true);
        check(quest() == reloaded && reloaded.definition == 42 && reloaded.progress.get(OFFLINE) == 89,
            "administrator server reload remains authoritative despite old network snapshot");
        event(DBType.QUEST);
        resetDelivery();
        NetQuestSync.quickSync(null, true, true);
        BQThreadedIO.INSTANCE.drain();
        for (betterquesting.network.PacketQuesting packet : BetterQuesting.instance.network.delivered) {
            receive(NetQuestSync.class, packet.tag, true);
        }
        check(quest() == reloaded && reloaded.progress.get(ONLINE) == 55 && reloaded.progress.get(OFFLINE) == 89,
            "runtime quickSync retains new definitions and all users after actual server reload");
    }

    private static void remoteSync() throws Exception {
        reset(false, false);
        login();
        NetQuestSync.sendSync(null, null, true, false);
        BQThreadedIO.INSTANCE.drain();
        NBTTagCompound config = delivered();
        Quest stale = new Quest();
        stale.definition = -1;
        stale.progress.put(OFFLINE, 999);
        QuestDatabase.INSTANCE.put(QUEST, stale);
        receive(NetQuestSync.class, config, true);
        check(quest() != stale && quest().definition == 3 && quest().progress.isEmpty(),
            "remote full sync still replaces definitions and clears stale client state");
        check(QuestDatabase.INSTANCE.clears == 1, "remote clear remains native");
        event(DBType.QUEST);

        resetDelivery();
        quest().progress.put(ONLINE, 34);
        NetQuestSync.sendSync(FMLCommonHandler.instance().server.manager.playerEntityList.get(0), null, false, true, true);
        BQThreadedIO.INSTANCE.drain();
        NBTTagCompound progress = delivered();
        quest().progress.put(OFFLINE, 144);
        quest().progress.put(ONLINE, 0);
        receive(NetQuestSync.class, progress, true);
        check(quest().progress.get(ONLINE) == 34 && !quest().progress.containsKey(OFFLINE),
            "remote resetCompletion still replaces stale progress");
        event(DBType.QUEST);

        resetDelivery();
        NetQuestSync.sendSync(null, Collections.singletonList(QUEST), true, false);
        BQThreadedIO.INSTANCE.drain();
        Quest before = quest();
        before.definition = -7;
        receive(NetQuestSync.class, delivered(), true);
        check(quest() == before && before.definition == 3, "remote partial config still applies without whole database clear");
    }

    private static void chapterSync() throws Exception {
        reset(true, true);
        login();
        Chapter original = new Chapter(); original.definition = 10;
        QuestLineDatabase.INSTANCE.put(CHAPTER, original);
        NetChapterSync.sendSync(null, null);
        BQThreadedIO.INSTANCE.drain();
        NBTTagCompound payload = delivered();
        original.definition = 11;
        receive(NetChapterSync.class, payload, true);
        check(QuestLineDatabase.INSTANCE.get(CHAPTER) == original && original.definition == 11,
            "shared chapter snapshot must not revert server edits or replace chapter identity");
        check(QuestLineDatabase.INSTANCE.clears == 0, "shared chapters not cleared");
        event(DBType.CHAPTER);
        Minecraft.getMinecraft().integrated = false;
        Minecraft.getMinecraft().handler.manager.local = false;
        receive(NetChapterSync.class, payload, true);
        check(QuestLineDatabase.INSTANCE.get(CHAPTER) != original
            && ((Chapter) QuestLineDatabase.INSTANCE.get(CHAPTER)).definition == 10,
            "remote full chapter synchronization retains native replacement semantics");
        event(DBType.CHAPTER);
    }

    private static void loaderAndSessionBoundaries() {
        CoreLateMixinLoader loader = new CoreLateMixinLoader();
        FMLLaunchHandler.current = Side.CLIENT;
        check(loader.getMixins(Collections.emptySet()).isEmpty(), "BQ absent => no optional target loaded");
        check(loader.getMixins(Collections.singleton("betterquesting")).equals(
            Arrays.asList("bq.MixinNetQuestSync", "bq.MixinNetChapterSync")), "client BQ selects both guards");
        FMLLaunchHandler.current = Side.SERVER;
        check(loader.getMixins(Collections.singleton("betterquesting")).isEmpty(), "dedicated server loads no client guard");
        Minecraft mc = Minecraft.getMinecraft();
        mc.integrated = true; mc.handler = new NetHandlerPlayClient(); mc.handler.manager.local = false;
        check(!SharedQuestDatabase.isLocalHost(), "stale integrated flag does not guard remote TCP");
        mc.handler = null;
        check(!SharedQuestDatabase.isLocalHost(), "no active handler does not imply shared session");
        mc.handler = new NetHandlerPlayClient(); mc.integrated = false;
        check(!SharedQuestDatabase.isLocalHost(), "local channel alone is not an integrated shared database");
        mc.integrated = true;
        check(SharedQuestDatabase.isLocalHost(), "active integrated local channel protects shared database until teardown");
    }

    private static Quest reset(boolean integrated, boolean local) {
        BQThreadedIO.INSTANCE.queue.clear();
        FMLCommonHandler.instance().server.manager.playerEntityList.clear();
        QuestDatabase.INSTANCE.clear(); QuestDatabase.INSTANCE.clears = 0;
        QuestLineDatabase.INSTANCE.clear(); QuestLineDatabase.INSTANCE.clears = 0;
        Minecraft.getMinecraft().integrated = integrated;
        Minecraft.getMinecraft().handler = new NetHandlerPlayClient();
        Minecraft.getMinecraft().handler.manager.local = local;
        resetDelivery();
        Quest quest = new Quest(); quest.definition = 3;
        quest.progress.put(ONLINE, 7); quest.progress.put(OFFLINE, 13);
        QuestDatabase.INSTANCE.put(QUEST, quest);
        quest.claims.put(ONLINE, 1); quest.claims.put(OFFLINE, 2);
        BQApi.calls = 0; BQManagedQuestProgress.calls = 0;
        betterquesting.handlers.SaveLoadHandler.INSTANCE.dirty = 0;
        return quest;
    }

    private static void login() {
        FMLCommonHandler.instance().server.manager.playerEntityList.add(new EntityPlayerMP(ONLINE));
    }

    private static void resetDelivery() {
        BetterQuesting.instance.network.delivered.clear();
        MinecraftForge.EVENT_BUS.events.clear();
    }

    private static Quest quest() { return (Quest) QuestDatabase.INSTANCE.get(QUEST); }
    private static NBTTagCompound delivered() { return BetterQuesting.instance.network.delivered.get(0).tag; }

    private static void receive(Class<?> nativeHandler, NBTTagCompound payload, boolean guarded) throws Exception {
        if (guarded) {
            Class<?> mixin = Class.forName("com.miaokatze.miaokatzecore.mixin.bq.Mixin" + nativeHandler.getSimpleName());
            String method = nativeHandler == NetQuestSync.class ? "core$keepSharedQuests" : "core$keepSharedChapters";
            Method injection = mixin.getDeclaredMethod(method, NBTTagCompound.class, CallbackInfo.class);
            injection.setAccessible(true);
            CallbackInfo info = new CallbackInfo();
            injection.invoke(null, payload, info);
            if (info.cancelled) return;
        }
        Method receive = nativeHandler.getDeclaredMethod("onClient", NBTTagCompound.class);
        receive.setAccessible(true);
        receive.invoke(null, payload);
    }

    private static void event(DBType type) {
        check(MinecraftForge.EVENT_BUS.events.size() == 1
            && ((DatabaseEvent) MinecraftForge.EVENT_BUS.events.get(0)).getType() == type,
            "exactly one native-compatible " + type + " UI update event");
        MinecraftForge.EVENT_BUS.events.clear();
    }

    private static void check(boolean condition, String message) {
        checks++;
        if (!condition) throw new AssertionError(message);
    }
}
