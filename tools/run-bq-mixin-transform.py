"""Headless real Mixin apply, followed by execution of untouched transformed client methods.

Requires fixture sources generated by run-bq-shared-sync-contracts.py. Those sources
are copied into the output directory; no source/production files are rewritten.
"""
import argparse
from pathlib import Path
import os
import re
import shutil
import subprocess

p = argparse.ArgumentParser()
p.add_argument('--classpath', type=Path, required=True, help='Native dependency classpath file (semicolon-separated on Windows)')
p.add_argument('--fixtures', type=Path, required=True, help='Generated dependency fakes directory')
p.add_argument('--output', type=Path, required=True)
p.add_argument('--java-home', type=Path, default=Path('D:/Program/Java'))
a = p.parse_args()
root = Path(__file__).resolve().parents[1]
out = a.output.resolve()
out.mkdir(parents=True, exist_ok=True)
java, javac = (str(a.java_home / 'bin' / name) for name in ('java.exe', 'javac.exe'))
native = a.classpath.read_text(encoding='utf-8-sig').strip().split(os.pathsep)
selected = [x for x in native if any(token in x.lower() for token in
    ('unimixins', 'launchwrapper', 'asm-debug', 'commons-io', 'log4j', 'jopt-simple', 'gson', 'guava', 'patchedmc', 'commons-lang3'))]
cache = Path.home() / '.gradle/caches/modules-2/files-2.1/com.github.GTNewHorizons/BetterQuesting/3.8.92-GTNH'
bq = next(cache.glob('*/BetterQuesting-3.8.92-GTNH-dev.jar'))
classes = out / 'classes'
classes.mkdir(exist_ok=True)
cp = os.pathsep.join(map(str, [classes, root / 'build/classes/java/main', root / 'src/main/resources', *selected, bq]))
(out / 'classpath.txt').write_text(cp, encoding='utf-8')

def run(command, log):
    result = subprocess.run(command, cwd=out, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, encoding='utf-8', errors='replace')
    (out / log).write_text(result.stdout, encoding='utf-8')
    for line in result.stdout.splitlines():
        if line.startswith('PASS'):
            print(line)
    if result.returncode:
        raise RuntimeError(f'{log} failed (exit {result.returncode}); see {out / log}')

run([javac, '-proc:none', '--release', '8', '-cp', cp, '-d', str(classes),
     str(root / 'tools/tests/BQMixinTransformRegression.java')], 'transform-compile.log')
run([java, '-Djava.awt.headless=true', '-cp', cp, 'BQMixinTransformRegression', str(out)], 'transform.log')

fakes = out / 'binary-compatible-fakes'
shutil.copytree(a.fixtures, fakes, dirs_exist_ok=True)
# Source regression fakes intentionally use convenient concrete types. The official
# jar uses erased NBTBase and the real Forge EventBus descriptors: restore those
# descriptors in this private copy for executing its unchanged instruction bodies.
for name in ('NBTTagCompound', 'NBTTagList'):
    path = fakes / f'net/minecraft/nbt/{name}.java'
    text = path.read_text().replace(f'class {name} {{', f'class {name} extends NBTBase {{')
    if name == 'NBTTagCompound':
        text = text.replace('void setTag(String key, Object value)', 'void setTag(String key, NBTBase value)')
    path.write_text(text)
(fakes / 'net/minecraft/nbt/NBTBase.java').write_text('package net.minecraft.nbt; public abstract class NBTBase {}')
for name in ('IQuest', 'IQuestLine'):
    path = fakes / f'betterquesting/api/questing/{name}.java'
    text = path.read_text().replace('void readFromNBT(net.minecraft.nbt.NBTTagCompound tag', 'void readFromNBT(net.minecraft.nbt.NBTBase tag')
    text = text.replace('void readProgressFromNBT(net.minecraft.nbt.NBTTagCompound tag', 'void readProgressFromNBT(net.minecraft.nbt.NBTBase tag')
    path.write_text(text)
for name in ('QuestDatabase', 'QuestLineDatabase'):
    path = fakes / f'betterquesting/questing/{name}.java'
    text = path.read_text()
    for method in ('readFromNBT', 'readProgressFromNBT'):
        text = re.sub(r'void ' + method + r'\(net\.minecraft\.nbt\.NBTTagCompound tag([^)]*)\)\s*\{',
            lambda match: f'void {method}(net.minecraft.nbt.NBTBase raw{match.group(1)}) {{ net.minecraft.nbt.NBTTagCompound tag = (net.minecraft.nbt.NBTTagCompound) raw;', text)
    path.write_text(text)
(fakes / 'cpw/mods/fml/common/eventhandler/EventBus.java').write_text('''package cpw.mods.fml.common.eventhandler;
public class EventBus { public final java.util.List<Event> events = new java.util.ArrayList<>();
public boolean post(Event event) { events.add(event); return false; } }''')
(fakes / 'net/minecraftforge/common/MinecraftForge.java').write_text('''package net.minecraftforge.common;
public class MinecraftForge { public static final cpw.mods.fml.common.eventhandler.EventBus EVENT_BUS = new cpw.mods.fml.common.eventhandler.EventBus(); }''')
fake_sources = [str(x) for x in fakes.rglob('*.java') if 'org/spongepowered' not in x.as_posix()]
fixture_classes = out / 'fixture-classes'
fixture_classes.mkdir(exist_ok=True)
um = next(x for x in selected if 'unimixins' in x)
runtime_cp = os.pathsep.join(map(str, [out / 'isolated', fixture_classes, root / 'build/classes/java/main', um, bq]))
run([javac, '-proc:none', '--release', '8', '-cp', runtime_cp, '-d', str(fixture_classes),
     *fake_sources, str(root / 'tools/tests/BQTransformedClientRegression.java')], 'execution-compile.log')
run([java, '-Djava.awt.headless=true', '-cp', runtime_cp, 'BQTransformedClientRegression'], 'execution.log')
print(f'Artifacts: {out}')
